#!/usr/bin/env node
// Generates src/rendering/DungeonManifest.js — the single source of truth for
// dungeon content.
//
// Bootstraps from reality: current engine pools become each prop's placement,
// and anything on disk without a pool is classified so it stops being invisible.
// Re-runnable; hand-edits to CLASSIFY below are what persist.

import fs from 'fs';
import path from 'path';
import { scanDisk, scanEngine, scanThemeTextures, ROOT } from './lib/content-index.mjs';

// Placement for props the engine never referenced. `blocked` means the asset is
// fine but no system can place it yet — tracked explicitly so it reads as
// "waiting on a feature" rather than silently missing.
const CLASSIFY = {
  boss_banner_large: 'wall', brazier_ornate_boss: 'wall', stained_glass_window: 'wall',
  wall_torch_iron: 'wall', ritual_brazier_lit: 'wall', ritual_chains_dangling: 'wall',
  prayer_pew: 'wall', rusted_armor_pile: 'wall', ossuary_skull_arch: 'wall',
  hanging_lantern: 'wall', skull_chandelier: 'wall',
  throne_massive: 'center', throne_dais: 'center', ossuary_bone_throne: 'center',
  sacrificial_pedestal: 'center', ritual_demon_statue: 'center', lever_pillar: 'center',
  scattered_books: 'scatter',
  // Hazards are placed by the server as wing features (server/dungeon/
  // hazards.js) with explicit coordinates, not scattered by the client, so
  // they get their own placement rather than a decoration pool.
  spike_trap: 'hazard', pressure_plate: 'hazard',
  swinging_blade: 'hazard', fire_vent: 'hazard',
  // Still blocked: architecture needs the spatial generator to place stairs,
  // bridges and gates somewhere meaningful.
  stairs_ascending: 'blocked:architecture', stairs_descending: 'blocked:architecture',
  stone_bridge: 'blocked:architecture', gate_archway: 'blocked:architecture',
  runic_door_sealed: 'blocked:architecture',
};

const disk = scanDisk();
const eng = scanEngine();
const themes = scanThemeTextures();

// A prop legitimately belongs to several pools at once — `buttress` is both a
// horizon ring piece and a corner piece — so placements is a list. Collapsing
// it to one value silently emptied the smaller pools.
const placementsOf = (id) => {
  // CLASSIFY wins. scanEngine now derives pools from the manifest this script
  // regenerates, so reading pools first would feed a stale value straight back
  // in — a prop could never be reclassified once written (e.g. promoting a
  // hazard out of `blocked:` after building the system that places it).
  if (CLASSIFY[id]) return [CLASSIFY[id]];
  const pools = Object.entries(eng.pools)
    .filter(([, ids]) => ids.includes(id))
    .map(([pool]) => pool);
  if (pools.length) return pools;
  return [eng.referenced.has(id) ? 'special' : 'unclassified'];
};

const props = disk.props.map(id => ({
  id,
  placements: placementsOf(id),
  destructible: eng.flags.destructible.includes(id),
  cloth: eng.flags.cloth.includes(id),
})).sort((a, b) => a.placements[0].localeCompare(b.placements[0]) || a.id.localeCompare(b.id));

// Which themes want which texture — lets the renderer honour a theme's declared
// art instead of reading its own hardcoded names.
const texThemes = {};
// scanThemeTextures returns { all, live, inert } per theme — `all` is what we
// want here, since the manifest records every texture a theme names.
for (const [theme, info] of Object.entries(themes)) {
  for (const t of (info.all || [])) (texThemes[t] ||= []).push(theme);
}
const roleOf = (id) => id.startsWith('floor_') ? 'floor'
  : id.startsWith('wall_') ? 'wall'
  : id.startsWith('ceiling_') ? 'ceiling'
  : id.startsWith('decal_') ? 'decal' : 'misc';

const textures = disk.textures.map(id => ({
  id, role: roleOf(id), themes: texThemes[id] || [],
})).sort((a, b) => a.role.localeCompare(b.role) || a.id.localeCompare(b.id));

const q = (s) => `'${s}'`;
const out = `// GENERATED by scripts/bootstrap-dungeon-manifest.mjs — re-run to refresh.
//
// Single source of truth for dungeon content. The engine derives its placement
// pools from PROPS rather than hardcoding a dozen separate arrays, and themes
// resolve their textures through TEXTURES. Declaring an asset here is what makes
// it both generated and consumed, which is what stops the two sides drifting.
//
// placement: wall | corner | center | scatter | cluster | ring | pillar | rubble
//            | arch | hanging | special      — placeable today
//            | blocked:<system>              — asset is fine, no system places it
//            | unclassified                  — needs a decision
// A prop may carry several placements; poolFor() matches any of them.
//
// Run \`npm run content:check\` after editing.

export const PROPS = [
${props.map(p => `  { id: ${q(p.id)}, placements: [${p.placements.map(q).join(', ')}]${p.destructible ? ', destructible: true' : ''}${p.cloth ? ', cloth: true' : ''} },`).join('\n')}
];

export const TEXTURES = [
${textures.map(t => `  { id: ${q(t.id)}, role: ${q(t.role)}, themes: [${t.themes.map(q).join(', ')}] },`).join('\n')}
];

/** Prop ids for a placement pool, excluding anything blocked or unclassified. */
export function poolFor(placement) {
  return PROPS.filter(p => p.placements.includes(placement)).map(p => p.id);
}

export const DESTRUCTIBLE = PROPS.filter(p => p.destructible).map(p => p.id);
export const CLOTH = PROPS.filter(p => p.cloth).map(p => p.id);

/** Textures a theme declares for a role, most specific first. */
export function themeTexture(themeId, role) {
  const t = TEXTURES.find(x => x.role === role && x.themes.includes(themeId));
  return t ? t.id : null;
}

export const BLOCKED = PROPS
  .filter(p => p.placements.some(x => x.startsWith('blocked:')))
  .map(p => ({ id: p.id, system: p.placements.find(x => x.startsWith('blocked:')).split(':')[1] }));
`;

fs.writeFileSync(path.join(ROOT, 'src', 'rendering', 'DungeonManifest.js'), out);

const byPlacement = {};
for (const p of props) for (const pl of p.placements) byPlacement[pl] = (byPlacement[pl] || 0) + 1;
console.log(`DungeonManifest.js written — ${props.length} props, ${textures.length} textures`);
for (const [k, v] of Object.entries(byPlacement).sort()) console.log(`   ${k.padEnd(24)} ${v}`);
