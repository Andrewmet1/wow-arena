#!/usr/bin/env node
// Extract per-clip combat timing: when the blow lands, and how much of the
// clip is worth showing.
//
// The clips are full performances — 1.9-4.4s of genuine motion, only 2-23% of
// it dead time, so trimming padding does not help. But the part that reads as
// the attack is short: windup through impact is 0.6-1.6s, and everything after
// is a long settle back to idle that a player never needs to see.
//
// Scaling the whole clip into a 1.5s GCD therefore meant 1.2-2.9x — visibly
// fast-forwarded. Playing only to impact plus a short follow-through needs
// 0.4-1.2x instead: natural speed, with the tail blended out rather than
// rushed through. That is what "early-exit frames" means in practice, and it
// is why WoW's 1.5s swing reads correctly — the animation ends when the
// ability does.
//
//   node scripts/generate-clip-timing.mjs

import fs from 'fs';
import path from 'path';

const RIGS = path.resolve('public/assets/animations/rigs');
const OUT = path.resolve('src/rendering/ClipTiming.js');
const RECOVERY = 0.25;      // follow-through kept after impact, in seconds

function analyse(file) {
  const buf = fs.readFileSync(file);
  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  const jl = dv.getUint32(12, true);
  const js = JSON.parse(new TextDecoder().decode(buf.slice(20, 20 + jl)));
  const binOff = 20 + jl + 8;
  const read = (i) => {
    const a = js.accessors[i], bv = js.bufferViews[a.bufferView];
    const start = binOff + (bv.byteOffset || 0) + (a.byteOffset || 0);
    if (a.componentType !== 5126) return null;
    const n = { SCALAR: 1, VEC3: 3, VEC4: 4 }[a.type];
    const out = [];
    for (let i2 = 0; i2 < a.count; i2++) {
      const row = [];
      for (let c = 0; c < n; c++) row.push(dv.getFloat32(start + (i2 * n + c) * 4, true));
      out.push(n === 1 ? row[0] : row);
    }
    return out;
  };
  const anim = js.animations?.[0];
  if (!anim) return null;
  let times = null; const series = [];
  for (const ch of anim.channels) {
    if (ch.target.path !== 'rotation') continue;
    const smp = anim.samplers[ch.sampler];
    const t = read(smp.input), v = read(smp.output);
    if (!t || !v) continue;
    if (!times) times = t;
    if (t.length === times.length) series.push(v);
  }
  if (!times?.length || !series.length) return null;

  // Total angular change per keyframe across every bone. The peak is the
  // moment of greatest movement — the strike.
  const motion = new Array(times.length).fill(0);
  for (const v of series) {
    for (let i = 1; i < v.length; i++) {
      let d = 0;
      for (let c = 0; c < 4; c++) d += Math.abs(v[i][c] - v[i - 1][c]);
      motion[i] += d;
    }
  }
  const duration = times[times.length - 1];
  const peak = Math.max(...motion);
  const thresh = peak * 0.06;
  const first = motion.findIndex(m => m > thresh);
  const impact = times[motion.indexOf(peak)];
  const start = first > 0 ? times[first] : 0;
  const useful = Math.min(duration, impact + RECOVERY) - start;
  return {
    duration: +duration.toFixed(3),
    start: +start.toFixed(3),
    impact: +impact.toFixed(3),
    useful: +Math.max(0.2, useful).toFixed(3),
  };
}

const out = {};
for (const rig of fs.readdirSync(RIGS)) {
  const dir = path.join(RIGS, rig);
  if (!fs.statSync(dir).isDirectory() || rig.startsWith('_')) continue;
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith('.glb')) continue;
    try {
      const info = analyse(path.join(dir, f));
      if (info) out[f.slice(0, -4)] = info;
    } catch { /* unreadable clip: renderer falls back to whole-clip timing */ }
  }
}

const body = `// GENERATED by scripts/generate-clip-timing.mjs — re-run after changing clips.
//
// Per-clip combat timing. \`impact\` is the frame of greatest motion, i.e. when
// the blow lands; \`useful\` is start-to-impact plus a short follow-through.
// The renderer plays only the useful portion and blends out the settle, so a
// three-second performance can occupy a 1.5s GCD at natural speed instead of
// being fast-forwarded into it.
export const CLIP_TIMING = ${JSON.stringify(out, null, 2)};

/** Timing for a clip, or null when it has none (renderer uses whole-clip). */
export function clipTiming(name) {
  return CLIP_TIMING[name] ?? null;
}
`;
fs.writeFileSync(OUT, body);
const n = Object.keys(out).length;
const scales = Object.values(out).map(t => t.useful / 1.5);
console.log(`\n  ${n} clips analysed -> src/rendering/ClipTiming.js`);
console.log(`  scale to a 1.5s GCD: ${Math.min(...scales).toFixed(2)}x - ${Math.max(...scales).toFixed(2)}x`);
console.log(`  (whole-clip scaling was 1.24x - 2.93x)\n`);
